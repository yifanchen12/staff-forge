"""Select only used assets, keep source packs separate, author a quiet loop."""
from pathlib import Path
import json
import math
import shutil
import struct
import wave

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
used = []

def copy(source, destination, attribution):
    source, destination = ASSETS / source, ASSETS / destination
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination)
    used.append({"path": destination.relative_to(ROOT).as_posix(), **attribution})

def main():
    furniture = {"source": "https://kenney.nl/assets/furniture-kit", "license": "CC0-1.0"}
    for name in ["bookcaseOpen", "books", "chair", "tableCross", "plantSmall1"]:
        copy(f"kenney/furniture-kit/Models/GLTF format/{name}.glb", f"models/{name}.glb", furniture)
    dungeon = {"source": "https://kenney.nl/assets/modular-dungeon-kit", "license": "CC0-1.0"}
    copy("kenney/modular-dungeon-kit/Models/GLB format/gate-door.glb", "models/gate-door.glb", dungeon)
    copy("kenney/modular-dungeon-kit/Models/GLB format/Textures/colormap.png", "models/Textures/colormap.png", dungeon)
    audio = {"source": "https://kenney.nl/assets/impact-sounds", "license": "CC0-1.0"}
    for name, target in [("impactMetal_medium_000", "infuse"), ("impactGlass_heavy_000", "break"),
                         ("impactBell_heavy_000", "bell"), ("impactGlass_light_000", "click"),
                         ("footstep_concrete_000", "step")]:
        copy(f"kenney/impact-sounds/Audio/{name}.ogg", f"audio/{target}.ogg", audio)
    for name in ["light_01", "magic_01", "smoke_01"]:
        copy(f"kenney/particle-pack/PNG (Transparent)/{name}.png", f"particles/{name}.png",
             {"source": "https://kenney.nl/assets/particle-pack", "license": "CC0-1.0"})
    (ASSETS / "licenses").mkdir(exist_ok=True)
    for slug in ["furniture-kit", "modular-dungeon-kit", "impact-sounds", "particle-pack"]:
        shutil.copy2(ASSETS / "kenney" / slug / "License.txt", ASSETS / "licenses" / f"{slug}.txt")
    used.append({"path": "assets/fonts/NotoSansSC.ttf",
                 "source": "https://github.com/google/fonts/tree/main/ofl/notosanssc",
                 "license": "SIL Open Font License 1.1", "license_file": "assets/fonts/OFL.txt"})
    # Original periodic sine drone; authored here, not generated by an AI service.
    rate, seconds = 22050, 16
    frames = bytearray()
    for i in range(rate * seconds):
        t = i / rate
        modulation = 0.65 + 0.35 * math.cos(2 * math.pi * t / seconds)
        value = modulation * (0.16 * math.sin(2 * math.pi * 55 * t)
                              + 0.09 * math.sin(2 * math.pi * 82.5 * t)
                              + 0.05 * math.sin(2 * math.pi * 110 * t))
        frames += struct.pack("<h", int(32767 * value))
    with wave.open(str(ASSETS / "audio" / "ambience.wav"), "wb") as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(rate)
        output.writeframes(frames)
    used.append({"path": "assets/audio/ambience.wav", "source": "tools/prepare_assets.py", "license": "Original project asset"})
    (ASSETS / "used-assets.json").write_text(json.dumps(used, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Prepared {len(used)} used assets.")

if __name__ == "__main__":
    main()
